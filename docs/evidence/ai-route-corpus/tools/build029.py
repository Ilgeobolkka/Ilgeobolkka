CASE_REQUIRED_CONCEPTS = ["값 하나의 한계", "평균의 성질", "흔들림과 흐름", "이동평균", "평활의 대가",
                          "방향의 판정"]
CASE_HELPFUL_CONCEPTS = ["기준 기간", "날씨와 기후", "두 시점의 오해"]


def build_case(manifest_pages, prereq, seeds, irrelevant, alternatives):
    route = sorted(corpus_lib.prereq_closure(seeds, prereq))
    groups = {}
    for page in manifest_pages:
        for key in page["duplicateGroupKeys"]:
            groups.setdefault(key, []).append(page["pageNumber"])
    return {
        "caseId": f"case-book-{BOOK_ID:03d}",
        "bookId": BOOK_ID,
        "purpose": "이 책을 소장하고 있는데, 오르내리는 값에서 방향을 읽어 내는 방법과 그 방법이 "
                   "감추는 것을 제대로 익히고 싶다",
        "owned": True,
        "maxAdditionalInk": None,
        "depth": "BALANCED",
        "activeRentalPageNumbers": [],
        "requiredConcepts": CASE_REQUIRED_CONCEPTS,
        "helpfulConcepts": CASE_HELPFUL_CONCEPTS,
        "requiredPrerequisites": [
            {"beforePageNumber": before, "afterPageNumber": after}
            for after in route
            for before in sorted(prereq.get(after, []))
        ],
        "irrelevantPageNumbers": irrelevant,
        "duplicatePageGroups": [sorted(pages) for _, pages in sorted(groups.items())],
        "referencePageNumbers": route,
        "allowedAlternativePageNumbers": alternatives,
    }



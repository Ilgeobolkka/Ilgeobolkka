def build_case(manifest_pages, prereq):
    route = sorted(corpus_lib.prereq_closure(CASE_SEED_PAGES, prereq))
    groups = {}
    for page in manifest_pages:
        for key in page["duplicateGroupKeys"]:
            groups.setdefault(key, []).append(page["pageNumber"])
    return {
        "caseId": f"case-book-{BOOK_ID:03d}",
        "bookId": BOOK_ID,
        "purpose": "이 책을 사지는 않았고, 악보를 어디서 끊어 읽어야 하는지와 쉼을 얼마나 두어야 "
                   "하는지를 익히고 싶다",
        "owned": False,
        "maxAdditionalInk": 15,
        "depth": None,
        "activeRentalPageNumbers": [],
        "requiredConcepts": CASE_REQUIRED_CONCEPTS,
        "helpfulConcepts": CASE_HELPFUL_CONCEPTS,
        "requiredPrerequisites": [
            {"beforePageNumber": before, "afterPageNumber": after}
            for after in route
            for before in sorted(prereq.get(after, []))
        ],
        "irrelevantPageNumbers": CASE_IRRELEVANT_PAGES,
        "duplicatePageGroups": [sorted(pages) for _, pages in sorted(groups.items())],
        "referencePageNumbers": route,
        "allowedAlternativePageNumbers": CASE_ALTERNATIVE_PAGES,
    }


def main():
    pdf_sha256 = sys.argv[1] if len(sys.argv) > 1 else "0" * 64
    for index, paragraph in EXTRA.items():
        PAGES[index]["body"] += "\n\n" + paragraph

    numbered, prereq, toc_entries = corpus_lib.assemble(PAGES, SECTION_EDGES)
    manifest_pages, manuscript_pages = corpus_lib.build_pages(
        numbered,
        prereq,
        toc_topic="이 책이 다루는 차례와 각 장이 답하는 물음",
        toc_analysis="목차 페이지. 장과 절의 시작 위치만 담고 본문 설명은 없다.",
        toc_body_text=corpus_lib.toc_body(toc_entries),
    )
    corpus_lib.validate_book(manifest_pages, manuscript_pages)

    manuscript = {"bookId": BOOK_ID, "title": TITLE, "pages": manuscript_pages}
    (REPO / f"docs/evidence/ai-route-corpus/book-{BOOK_ID:03d}-manuscript.json").write_text(
        json.dumps(manuscript, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")

    book = {
        "bookId": BOOK_ID,
        "title": TITLE,
        "pdfPath": f"pdfs/book-{BOOK_ID:03d}.pdf",
        "pdfSha256": pdf_sha256,
        "totalPageCount": len(manifest_pages),
        "aiRouteCandidate": True,
        "aiExternalTransferAllowed": True,
        "pages": manifest_pages,
    }
    fragments = REPO / "docs/evidence/ai-route-corpus/_fragments"
    fragments.mkdir(exist_ok=True)
    (fragments / f"book-{BOOK_ID:03d}.json").write_text(
        json.dumps({"manifestBook": book, "evaluationCase": build_case(manifest_pages, prereq)},
                   ensure_ascii=False, indent=2)
        + "\n",
        encoding="utf-8")

    size = {
        page["pageNumber"]: len(corpus_lib.prereq_closure([page["pageNumber"]], prereq))
        for page in manifest_pages
        if page["aiRouteCandidatePage"]
    }
    chapters = {
        page["chapter"] for page in manifest_pages
        if page["aiRouteCandidatePage"] and size[page["pageNumber"]] <= 5
    }
    text_pages = [p for p in manuscript_pages if p["contentFormat"] == "TEXT" and p["pageNumber"] > 1]
    route = sorted(corpus_lib.prereq_closure(CASE_SEED_PAGES, prereq))
    print(f"페이지 {len(manifest_pages)} · TEXT {len(text_pages)} · IMAGE "
          f"{sum(1 for p in manuscript_pages if p['contentFormat'] == 'IMAGE')}")
    print(f"본문 {sum(len(p['body']) for p in text_pages):,}자 · "
          f"페이지당 {min(len(p['body']) for p in text_pages)}~{max(len(p['body']) for p in text_pages)}자")
    print(f"최대 폐쇄 {max(size.values())} · 폐쇄 ≤5 장수 {len(chapters)} · "
          f"≤15 비율 {sum(1 for v in size.values() if v <= 15) / len(size):.0%}")
    print(f"정답 경로 {len(route)}p {route}")
    print("validate_book 통과")


if __name__ == "__main__":
    main()
